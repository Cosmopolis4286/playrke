<h2>Información del Juego</h2>
<p>
    Jugar Bingo es muy sencillo y divertido, cada sala tiene un precio del Cartón diferente
    y diariamente se realizan varias partidas. Actualmente, solo se juegan con la modalidad de Cartón Lleno.
</p>
<h5>Juego:</h5>
<p>
    Cada cartón está compuesto por 24 números del 1 al 75,
    distribuidos en una cuadrícula de 5 filas por 5 columnas.
    Debes ir marcando los números a medida que vayan saliendo las Fichas,
    así que no debes despistarte y estar muy atento para cantar ¡Bingo! en tu carton ganador.
    </li>
<h5>Cómo Ganar:</h5>
<p>
    Debes cantar Bingo al tener Cartón Lleno.
    Proximamente, se anexaran nuevos cantos tales como: linea, 4 esquinas, cruz grande o cruz pequeña.
</p>
<h5>Modalidades:</h5>
<p><u>Modo Cartón Lleno</u>: En esta modalidad sólo se puede cantar Bingo al completar todos los números en tu cartón.</p>